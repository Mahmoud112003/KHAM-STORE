let currentLang = localStorage.getItem('siteLanguage') || 'en';

function getText(key, fallback = '') {
    const langMap = translations[currentLang] || translations.en;
    return langMap[key] || translations.en[key] || fallback;
}

function applyTranslations() {
    const lang = currentLang === 'ar' ? 'ar' : 'en';
    currentLang = lang;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.body?.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        const value = getText(key, el.textContent.trim());
        if (value) {
            el.textContent = value;
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const key = el.getAttribute('data-i18n-placeholder');
        const value = getText(key, el.getAttribute('placeholder'));
        if (value) {
            el.setAttribute('placeholder', value);
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
        const key = el.getAttribute('data-i18n-title');
        const value = getText(key, el.getAttribute('title'));
        if (value) {
            el.setAttribute('title', value);
        }
    });

    const currentLangEl = document.getElementById('currentLang');
    if (currentLangEl) {
        currentLangEl.textContent = lang === 'ar' ? 'العربية' : 'English';
    }

    document.querySelectorAll('.option').forEach((option) => {
        const optionValue = option.getAttribute('data-value') || option.getAttribute('data-lang');
        option.classList.toggle('active', optionValue === lang);
    });
}

function setLanguage(lang) {
    currentLang = lang === 'ar' ? 'ar' : 'en';
    localStorage.setItem('siteLanguage', currentLang);
    applyTranslations();
    window.dispatchEvent(new Event('languagechange'));
}

function bindLangSwitch() {
    document.querySelectorAll('.option').forEach((option) => {
        option.onclick = (event) => {
            event.preventDefault();
            const lang = option.getAttribute('data-value') || option.getAttribute('data-lang') || 'en';
            setLanguage(lang);
        };
    });
}

window.getText = getText;
window.setLanguage = setLanguage;
window.applyPageTranslations = applyTranslations;
window.getCurrentLanguage = () => currentLang;

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    bindLangSwitch();
});

window.addEventListener('load', () => {
    applyTranslations();
    bindLangSwitch();
});

window.addEventListener('languagechange', () => {
    setTimeout(() => {
        window.dispatchEvent(new Event('languagechange-applied'));
    }, 0);
});
